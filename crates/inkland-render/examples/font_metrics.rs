//! Write the table of font metrics that label placement uses.
//!
//! Run it with one `Family=path` argument for each font:
//!
//! ```text
//! cargo run -p inkland-render --example font_metrics -- \
//!     "IM Fell English=IMFellEnglish-Regular.ttf" ... > src/metrics_data.rs
//! ```
//!
//! A first argument `--name NAME` gives the table the name `NAME` in place
//! of `FONTS`. The cap height is the larger of the cap height of the font
//! and the top of its `H`.
//!
//! The table holds the advance width of each character from U+0020 to
//! U+024F, the cap height, and the descender. A width of 0 means that the
//! font has no glyph for the character.

use skrifa::FontRef;
use skrifa::MetadataProvider;
use skrifa::instance::{LocationRef, Size};
use std::fmt::Write as _;

const FIRST: u32 = 0x20;
const LAST: u32 = 0x24f;

fn main() {
    let mut out = String::new();
    out.push_str("//! Font metrics for label placement. This file is generated by\n");
    out.push_str("//! `examples/font_metrics.rs`. Do not edit it.\n\n");
    out.push_str("use crate::metrics::FontMetrics;\n\n");
    let mut args: Vec<String> = std::env::args().skip(1).collect();
    let name = if args.first().is_some_and(|a| a == "--name") && args.len() > 1 {
        let name = args.remove(1);
        args.remove(0);
        name
    } else {
        "FONTS".to_owned()
    };
    let _ = writeln!(out, "pub const {name}: [FontMetrics; {}] = [", args.len());
    for arg in &args {
        let (family, path) = arg.split_once('=').expect("argument is Family=path");
        let data = std::fs::read(path).expect("font file can be read");
        let font = FontRef::new(&data).expect("font file can be parsed");
        let m = font.metrics(Size::unscaled(), LocationRef::default());
        let glyphs = font.glyph_metrics(Size::unscaled(), LocationRef::default());
        let charmap = font.charmap();
        // Some fonts give a wrong cap height. The top of `H` is the cap
        // height too; the table keeps the larger of the two.
        let h_top = charmap
            .map('H')
            .and_then(|g| glyphs.bounds(g))
            .map_or(0.0, |b| b.y_max);
        let cap = libm::round(f64::from(m.cap_height.unwrap_or(m.ascent).max(h_top))) as i16;
        let descender = libm::round(f64::from(m.descent)) as i16;
        let _ = writeln!(out, "    FontMetrics {{");
        let _ = writeln!(out, "        family: {family:?},");
        let _ = writeln!(out, "        units_per_em: {},", m.units_per_em);
        let _ = writeln!(out, "        cap_height: {cap},");
        let _ = writeln!(out, "        descender: {descender},");
        let _ = writeln!(out, "        first: {FIRST:#x},");
        out.push_str("        advances: &[");
        for (i, code) in (FIRST..=LAST).enumerate() {
            if i % 16 == 0 {
                out.push_str("\n            ");
            } else {
                out.push(' ');
            }
            let advance = char::from_u32(code)
                .and_then(|c| charmap.map(c))
                .and_then(|g| glyphs.advance_width(g))
                .map_or(0, |a| libm::round(f64::from(a)) as u16);
            let _ = write!(out, "{advance},");
        }
        out.push_str("\n        ],\n    },\n");
    }
    out.push_str("];\n");
    print!("{out}");
}
